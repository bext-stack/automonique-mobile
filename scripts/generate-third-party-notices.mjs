import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const outputPath = join(root, 'THIRD_PARTY_NOTICES.generated.md');
const check = process.argv.includes('--check');

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function packageNameFromPath(path) {
  const marker = 'node_modules/';
  const index = path.lastIndexOf(marker);
  return index < 0 ? null : path.slice(index + marker.length);
}

async function licenseTexts(packageRoot) {
  let names;
  try {
    names = await readdir(packageRoot);
  } catch {
    return [];
  }
  const candidates = names
    .filter((name) =>
      /^(?:license|licence|copying|notice)(?:[._-]|$)/iu.test(name),
    )
    .sort((left, right) => left.localeCompare(right));
  const texts = [];
  for (const name of candidates) {
    const path = join(packageRoot, name);
    try {
      if (!(await stat(path)).isFile()) continue;
      const text = (await readFile(path, 'utf8'))
        .replaceAll('\r\n', '\n')
        .split('\n')
        .map((line) => line.trimEnd())
        .join('\n')
        .trim();
      if (text.length > 0 && !texts.includes(text)) texts.push(text);
    } catch {
      // The lockfile entry remains represented even if an optional notice file
      // cannot be read from the installed package.
    }
  }
  return texts;
}

const lock = JSON.parse(
  await readFile(join(root, 'package-lock.json'), 'utf8'),
);
if (lock.lockfileVersion !== 3 || typeof lock.packages !== 'object') {
  throw new Error('package_lock_v3_required');
}

const packages = [];
for (const path of Object.keys(lock.packages).sort()) {
  if (path === '') continue;
  const locked = lock.packages[path];
  const fallbackName = packageNameFromPath(path);
  const manifestPath = join(root, path, 'package.json');
  let manifest = {};
  try {
    manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch {
    // npm may omit platform-specific optional packages. The lockfile remains
    // authoritative for their identity and declared license.
  }
  const name = manifest.name ?? fallbackName;
  const version = manifest.version ?? locked.version;
  if (typeof name !== 'string' || typeof version !== 'string') {
    throw new Error(`package_identity_missing:${path}`);
  }
  const legacyLicenses = Array.isArray(manifest.licenses)
    ? manifest.licenses
        .map((entry) =>
          typeof entry === 'object' && entry !== null ? entry.type : null,
        )
        .filter((entry) => typeof entry === 'string')
    : [];
  const declaredLicense =
    typeof manifest.license === 'string'
      ? manifest.license
      : legacyLicenses.length > 0
        ? legacyLicenses.join(' OR ')
        : typeof locked.license === 'string'
          ? locked.license
          : 'NOASSERTION';
  if (declaredLicense === 'NOASSERTION') {
    throw new Error(`package_license_missing:${name}@${version}`);
  }
  const texts = await licenseTexts(join(root, path));
  packages.push({ declaredLicense, name, path, texts, version });
}

const identities = new Set();
for (const entry of packages) {
  const identity = `${entry.path}\0${entry.name}\0${entry.version}`;
  if (identities.has(identity))
    throw new Error(`package_duplicate:${entry.path}`);
  identities.add(identity);
}

const groups = new Map();
for (const entry of packages) {
  const combinedText = entry.texts.join(
    '\n\n--- bundled notice boundary ---\n\n',
  );
  const key =
    combinedText.length > 0
      ? digest(combinedText)
      : `metadata:${entry.declaredLicense}`;
  const group = groups.get(key) ?? {
    declaredLicenses: new Set(),
    packages: [],
    text: combinedText,
  };
  group.declaredLicenses.add(entry.declaredLicense);
  group.packages.push(`${entry.name}@${entry.version} (${entry.path})`);
  groups.set(key, group);
}

const lines = [
  '# Generated third-party notices',
  '',
  '<!-- Generated by scripts/generate-third-party-notices.mjs. Do not edit. -->',
  '',
  `This inventory covers all ${packages.length} installed dependency locations in the npm v3 lockfile.`,
  'Repeated license texts are grouped without dropping package identity. Packages that do not',
  'ship a discoverable license/notice file are still listed under their declared SPDX expression.',
  '',
];

const orderedGroups = [...groups.entries()].sort(([left], [right]) =>
  left.localeCompare(right),
);
for (const [key, group] of orderedGroups) {
  lines.push(
    `## ${key.startsWith('metadata:') ? 'Declared metadata only' : `License text SHA-256 ${key}`}`,
  );
  lines.push('');
  lines.push(
    `Declared license: ${[...group.declaredLicenses].sort().join(', ')}`,
  );
  lines.push('');
  lines.push('Packages:');
  lines.push('');
  for (const identity of group.packages.sort()) lines.push(`- ${identity}`);
  lines.push('');
  if (group.text.length > 0) {
    lines.push('```text');
    lines.push(group.text.replaceAll('```', '```\u200b'));
    lines.push('```');
    lines.push('');
  }
}

const generated = `${lines.join('\n').trimEnd()}\n`;
if (check) {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    throw new Error('third_party_notices_missing');
  }
  if (current !== generated) throw new Error('third_party_notices_stale');
} else {
  await writeFile(outputPath, generated);
}
